  name: 'post-pr-reviews',
  description: 'Re-verify each PR review finding against its head, then post one COMMENT review per PR with inline comments',
  phases: [
    { title: 'Verify', detail: 'independent skeptic re-checks each finding and finds its diff anchor' },
    { title: 'Post', detail: 'post one review per PR: summary body + inline comments' },
  ],
