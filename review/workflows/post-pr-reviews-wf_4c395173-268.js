const REPO = '/home/user/stt-api'
const SCRATCH = '/tmp/claude-0/-home-user-stt-api/349487e0-d09b-554f-9be8-0221f8cd653b/scratchpad'
const PY = SCRATCH + '/venv/bin/python'
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

const VERIFY = {
  type: 'object',
  properties: {
    headSha: { type: 'string' },
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          id: { type: 'string' },
          verdict: { type: 'string', enum: ['confirmed', 'plausible', 'refuted'] },
          evidence: { type: 'string', description: 'what you ran/traced and what it showed' },
          correction: { type: 'string', description: 'anything in the finding text that is wrong or should be reworded (numbers, line refs, claims); empty if none' },
          path: { type: 'string', description: 'repo-relative file for the inline anchor; empty string if no line in the PR diff fits' },
          line: { type: 'integer', description: 'RIGHT-side line number in the PR head that is inside a diff hunk; 0 if none' },
          startLine: { type: 'integer', description: 'first line for a multi-line anchor (same hunk, <= line); 0 for single line' },
        },
        required: ['id', 'verdict', 'evidence', 'correction', 'path', 'line', 'startLine'],
      },
    },
    nits: {
      type: 'array',
      items: {
        type: 'object',
        properties: { text: { type: 'string' }, keep: { type: 'boolean' }, why: { type: 'string' } },
        required: ['text', 'keep', 'why'],
      },
    },
  },
  required: ['headSha', 'findings', 'nits'],
}

const POSTED = {
  type: 'object',
  properties: {
    posted: { type: 'boolean' },
    reviewUrl: { type: 'string' },
    inlineCount: { type: 'integer' },
    bodyOnlyFindings: { type: 'array', items: { type: 'string' } },
    dropped: { type: 'array', items: { type: 'string' } },
    notes: { type: 'string' },
  },
  required: ['posted', 'reviewUrl', 'inlineCount', 'bodyOnlyFindings', 'dropped', 'notes'],
}

function findingsText(pr) {
  return pr.findings.map(f => `### ${f.id} [${f.severity}] ${f.title}\n${f.detail}`).join('\n\n')
}

const verifyPrompt = pr => `You are an independent skeptic re-checking code-review findings on GitHub PR scagood/stt-api#${pr.number} ("${pr.title}") before they are posted publicly. Another reviewer produced them. Your job is to try to REFUTE each one, and to find where each should be anchored as an inline review comment. Do NOT post anything to GitHub, push, or modify ${REPO}.

Setup:
- Repo: ${REPO}. PR branch is fetched as origin/${pr.branch}; expected head ${pr.sha}. Confirm with \`git -C ${REPO} rev-parse origin/${pr.branch}\` and \`git -C ${REPO} ls-remote origin refs/heads/${pr.branch}\`; report the full head sha you verified against.
- Make your own worktree: \`git -C ${REPO} worktree add --detach ${SCRATCH}/wf${pr.number} origin/${pr.branch}\`; remove it at the end with \`git -C ${REPO} worktree remove --force ${SCRATCH}/wf${pr.number}\`. Put throwaway scripts under ${SCRATCH}/wf${pr.number}-scripts/, not in the repo.
- Python 3.14 venv with test deps: ${PY} (run pytest / scripts from inside your worktree so imports resolve to the PR code). Main's own code is at origin/main if you need to compare.
- The PR diff GitHub shows is \`git diff origin/main...origin/${pr.branch}\` (three dots). Inline comments can only go on RIGHT-side lines inside those hunks.
${pr.context ? '\nContext:\n' + pr.context + '\n' : ''}
Findings to check:

${findingsText(pr)}

Nits to check:
${pr.nits.map((n, i) => `N${i + 1}. ${n}`).join('\n')}

For each finding:
1. Reproduce it yourself (write and run a small script against the PR code, or trace the exact code path with real values). Default to 'refuted' only if you show concrete evidence it is wrong; 'plausible' if you could not reproduce but could not disprove it; 'confirmed' if your own run/trace shows it. Check the numbers quoted (ranges, counts, line numbers) and put any fixes in 'correction'.
2. For "pre-existing / also on main" claims, confirm against origin/main too.
3. If a suggested fix is given, sanity-check that it does what it says (run it if cheap). Note problems in 'correction'.
4. Pick the inline anchor: the RIGHT-side line (and optional startLine) in the PR head that the finding is about, and that lies within a hunk of the three-dot diff. If the relevant code is not in the diff, give path '' and line 0.
For each nit: keep=true if accurate and worth saying, else keep=false with why.`

const postPrompt = (pr, v) => `Post ONE code review on GitHub PR scagood/stt-api#${pr.number} ("${pr.title}") using the GitHub MCP tools. Load them with ToolSearch: "select:mcp__github__pull_request_review_write,mcp__github__add_comment_to_pending_review,mcp__github__pull_request_read".

Steps:
1. Idempotency: fetch existing reviews (pull_request_read method get_reviews) and existing review comments. If any review body already contains the marker \`<!-- claude-review:pr-${pr.number} -->\`, do NOT post again — return posted=false with that review's URL. If you have a stale PENDING review on this PR, delete it first (pull_request_review_write method delete_pending).
2. Head check: get the PR (method get). If head sha is not ${v.headSha}, do NOT post; return posted=false explaining the mismatch.
3. Create a pending review (pull_request_review_write method create, no event).
4. Add one inline comment per finding that has a non-empty path and line > 0 (add_comment_to_pending_review, subjectType LINE, side RIGHT, path, line, and startLine/startSide RIGHT when startLine > 0). If adding a comment fails because the line is not in the diff, move that finding into the review body instead and record it in bodyOnlyFindings.
5. Submit the pending review (pull_request_review_write method submit_pending) with event COMMENT (never APPROVE or REQUEST_CHANGES) and the body below.
6. Return the review URL (html_url, or https://github.com/scagood/stt-api/pull/${pr.number}#pullrequestreview-<id>), how many inline comments landed, which findings are body-only, which were dropped.

Which findings to include:
- verdict 'confirmed': include as stated (apply 'correction' text if any).
- verdict 'plausible': include, but word it as unconfirmed ("I couldn't reproduce this directly, but…").
- verdict 'refuted': DROP. List it in 'dropped'.
- Nits: only those with keep=true.

Writing style (this is the repo owner's preference): direct and concise, clear simple wording but keep needed technical terms, neutral and respectful. No hype, no filler, no emoji. Do not name any AI model. Use the severity labels as given (e.g. **Medium**, **Low**).

Inline comment format (each one):
**<Severity>: <one-line problem>**
<1–3 sentences: what goes wrong and why>
Repro: <concrete input → actual vs expected>
Suggested fix: <short; code block if a one-liner/snippet was given>
${'Then end EVERY inline comment with this footer exactly (blank line, rule, italic line):'}
\`\`\`${FOOTER}
\`\`\`

Review body format:
<!-- claude-review:pr-${pr.number} -->
**Review summary** — 1–2 sentences on what the PR does and the overall verdict (no blocking bugs / etc.).
**Checked:** short bullet list of what was verified and test results (from the positives below).
${pr.crossPr ? '**Merge order / other PRs:** the cross-PR notes below, as bullets.\n' : ''}**Findings:** one bullet per included finding: severity + one-line summary + "(inline)" or the full detail if it is body-only.
**Nits:** bullets (omit section if none).
Then the footer exactly:
\`\`\`${FOOTER}
\`\`\`

Original findings (the full text, with repros and fixes):

${findingsText(pr)}

Nits (index N1..):
${pr.nits.map((n, i) => `N${i + 1}. ${n}`).join('\n')}

Positives / test results for the "Checked" section:
${pr.positives}
${pr.crossPr ? '\nCross-PR notes:\n' + pr.crossPr + '\n' : ''}
Independent verifier's results (verdicts, corrections, anchors) — this is authoritative over the original text where they differ:
${JSON.stringify(v, null, 2)}`

const results = await pipeline(
  args,
  pr => agent(verifyPrompt(pr), { label: `verify:#${pr.number}`, phase: 'Verify', schema: VERIFY }),
  (v, pr) => {
    if (!v) { log(`#${pr.number}: verifier failed; not posting`); return null }
    const refuted = v.findings.filter(f => f.verdict === 'refuted').map(f => f.id)
    if (refuted.length) log(`#${pr.number}: verifier refuted ${refuted.join(', ')} — will be dropped`)
    return agent(postPrompt(pr, v), { label: `post:#${pr.number}`, phase: 'Post', schema: POSTED })
      .then(p => ({ number: pr.number, verify: v, post: p }))
  },
)

return results.filter(Boolean).map(r => ({
  pr: r.number,
  verdicts: r.verify.findings.map(f => `${f.id}:${f.verdict}${f.correction ? ' (corrected)' : ''}`),
  corrections: r.verify.findings.filter(f => f.correction).map(f => `${f.id}: ${f.correction}`),
  nitsDropped: r.verify.nits.filter(n => !n.keep).map(n => `${n.text} — ${n.why}`),
  post: r.post,
}))
